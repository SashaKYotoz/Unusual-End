	private static class Tab extends CreativeModeTab {
		private final Supplier<ItemLike> icon;
		private final Supplier<List<ItemLike>> contents;
		private final Component title;

		private Tab(String id, Supplier<ItemLike> icon, Supplier<List<ItemLike>> contents) {
			super(UnusualEnd.MODID + "." + id);
			this.icon = icon;
			this.contents = contents;
			this.title = Component.translatable("item_group." + UnusualEnd.MODID + "." + id);
		}

		@Override
		public ItemStack makeIcon() {
			return new ItemStack(this.icon.get());
		}

		@Override
		public Component getDisplayName() {
			return this.title;
		}

		@Override
		public void fillItemList(NonNullList<ItemStack> items) {
			for (ItemLike item : this.contents.get())
				items.add(new ItemStack(item));
		}
	}
